#!/usr/bin/env python3
"""Generate animation selection from native item logic tables. No game assets."""
import json
import argparse
import re
from pathlib import Path
ROOT = Path(__file__).resolve().parents[2]
parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument('--native-root', type=Path, default=ROOT / 'vendor/melee-native')
parser.add_argument('--output', type=Path, default=ROOT / 'src/render3d/item-animations.generated.ts')
parser.add_argument('--check', action='store_true')
args = parser.parse_args()
NATIVE = args.native_root / 'src/melee/it'
OUT = args.output
def clean(s):
    return re.sub(r'/\*.*?\*/|//[^\n]*', '', s, flags=re.S)
def initializer(s, name):
    m = re.search(r'\b' + name + r'\s*\[[^;]*?=\s*\{', s)
    if not m: raise ValueError(name)
    start = i = m.end(); depth = 1
    while depth:
        if s[i] == '{': depth += 1
        elif s[i] == '}': depth -= 1
        i += 1
    return s[start:i-1]
def entries(body):
    depth = 0; start = 0; out = []
    for i,c in enumerate(body):
        if c == '{':
            if depth == 0: start = i+1
            depth += 1
        elif c == '}':
            depth -= 1
            if depth == 0: out.append(body[start:i])
    return out
states = {}
for p in sorted((NATIVE / 'kinds').glob('*.c')):
    s = clean(p.read_text())
    for name in re.findall(r'ItemStateTable\s+(\w+)\s*\[', s):
        body = initializer(s, name)
        rows = entries(body)
        if not rows:
            values = body.strip().rstrip(',').split(',')
            assert len(values) % 4 == 0, name
            rows = values[::4]
        values = [int(row.split(',')[0].strip(), 0) for row in rows]
        states[name] = (values, p.name)
# Native item.c chooses these arrays at the four ItemKind range boundaries.
registries = [('it_3F14.c','it_803F14C4',0,43), ('it_3F2F.c','it_803F3100',43,118),
              ('it_279C.c','it_803F23CC',161,47), ('it_3F2F.c','it_803F4D20',208,None)]
rows = []
for file,name,base,expected in registries:
    es = entries(initializer(clean((NATIVE/file).read_text()), name))
    if expected is not None: assert len(es) == expected, (name,len(es),expected)
    for i,e in enumerate(es):
        symbol = e.split(',')[0].strip()
        if symbol == 'NULL': continue
        offset = re.fullmatch(r'&(\w+)\[(\d+)\]', symbol)
        key = offset[1] if offset else symbol
        assert key in states, (name,i,symbol)
        values, source = states[key]
        if offset: values = values[int(offset[2]):]
        rows.append(f'  {hex(base+i)}: {json.dumps(values)}, // {source}: {symbol}')
generated = ('// Generated by scripts/melee-3d/generate-item-animations.py from melee-native.\n'
               '// Lucky Stats: item motion states are not animation indices. -1 means no animation.\n'
               'export const ITEM_ANIMATIONS: Readonly<Record<number, readonly number[]>> = {\n'+ '\n'.join(rows)+'\n};\n')
if args.check:
    if OUT.read_text() != generated: raise SystemExit('Item animation map differs from native tables')
else:
    OUT.write_text(generated)
print(f'{"Checked" if args.check else "Generated"} {len(rows)} item animation maps')
