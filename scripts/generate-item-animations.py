#!/usr/bin/env python3
"""Write src/render3d/item-animations.generated.ts: the animation each item state plays.

An item's state number is not the index of its animation: each item kind has a
table of states (the decompilation's ItemStateTable arrays), and the first field
of each entry is the animation that state plays (-1: none, the item keeps the
pose it had). This reads those tables from a checkout of the Melee
decompilation (https://github.com/doldecomp/melee) and writes that field for
every state of every item kind, in item-kind order. Only the numbers are
written; nothing is read from the game's own files.

    python scripts/generate-item-animations.py --native-root <decomp checkout>
    python scripts/generate-item-animations.py --native-root <decomp checkout> --check

--check compares with the file in the repository instead of writing it.
"""
import argparse
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]

parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
parser.add_argument("--native-root", type=Path, default=ROOT / "vendor/melee-native",
                    help="a doldecomp/melee checkout (default: vendor/melee-native)")
parser.add_argument("--output", type=Path, default=ROOT / "src/render3d/item-animations.generated.ts")
parser.add_argument("--check", action="store_true", help="compare with --output instead of writing it")
args = parser.parse_args()

ITEMS = args.native_root / "src/melee/it"

# The four tables item.c picks an item kind's state table from, by the range
# the kind is in: (file, table, first item kind, entries it must have, or None)
REGISTRIES = [
    ("it_3F14.c", "it_803F14C4", 0x00, 43),     # common items
    ("it_3F2F.c", "it_803F3100", 0x2B, 118),    # fighters' items
    ("it_279C.c", "it_803F23CC", 0xA1, 47),     # Pokemon
    ("it_3F2F.c", "it_803F4D20", 0xD0, None),   # stage items
]


def read(path):
    """a C file with its comments taken out"""
    text = path.read_text(encoding="utf-8", errors="replace")
    return re.sub(r"/\*.*?\*/|//[^\n]*", "", text, flags=re.S)


def initializer(text, name):
    """what is between the braces of `name[...] = { ... }`"""
    m = re.search(r"\b" + name + r"\s*\[[^;]*?=\s*\{", text)
    if not m:
        raise ValueError(f"no initializer for {name}")
    start = i = m.end()
    depth = 1
    while depth:
        if text[i] == "{":
            depth += 1
        elif text[i] == "}":
            depth -= 1
        i += 1
    return text[start:i - 1]


def entries(body):
    """the top-level { ... } entries of an initializer, each without its braces"""
    out = []
    depth = 0
    start = 0
    for i, c in enumerate(body):
        if c == "{":
            if depth == 0:
                start = i + 1
            depth += 1
        elif c == "}":
            depth -= 1
            if depth == 0:
                out.append(body[start:i])
    return out


def signed32(field):
    """a 32-bit field as C has it: 0xFFFFFFFF is -1"""
    v = int(field.strip(), 0) & 0xFFFFFFFF
    return v - 0x100000000 if v & 0x80000000 else v


# every item state table: its name -> (the animation of each state, its file)
tables = {}
for path in sorted((ITEMS / "kinds").glob("*.c")):
    text = read(path)
    for name in re.findall(r"ItemStateTable\s+(\w+)\s*\[", text):
        body = initializer(text, name)
        rows = entries(body)
        if not rows:
            # (a table written flat, four fields an entry)
            fields = body.strip().rstrip(",").split(",")
            assert len(fields) % 4 == 0, name
            rows = fields[::4]
        tables[name] = ([signed32(row.split(",")[0]) for row in rows], path.name)

lines = []
for file, name, first, expected in REGISTRIES:
    kinds = entries(initializer(read(ITEMS / file), name))
    if expected is not None:
        assert len(kinds) == expected, (name, len(kinds), expected)
    for i, entry in enumerate(kinds):
        symbol = entry.split(",")[0].strip()
        if symbol == "NULL":
            continue
        # (a kind whose states start part way into another's table: &table[n])
        offset = re.fullmatch(r"&(\w+)\[(\d+)\]", symbol)
        table = offset[1] if offset else symbol
        assert table in tables, (name, i, symbol)
        values, source = tables[table]
        if offset:
            values = values[int(offset[2]):]
        lines.append(f"  {hex(first + i)}: {json.dumps(values)}, // {source}: {symbol}")

generated = (
    "// Generated by scripts/generate-item-animations.py from the Melee decompilation's item state tables.\n"
    "// By item kind, the animation each of its states plays (the state number is not the animation's); -1: none.\n"
    "export const ITEM_ANIMATIONS: Readonly<Record<number, readonly number[]>> = {\n"
    + "\n".join(lines) + "\n};\n"
)
if args.check:
    if args.output.read_text(encoding="utf-8") != generated:
        raise SystemExit(f"{args.output} differs from the decompilation's tables")
else:
    args.output.write_text(generated, encoding="utf-8", newline="\n")
print(f"{'Checked' if args.check else 'Generated'} {len(lines)} item kinds")
